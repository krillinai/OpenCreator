export type TranslationKey = keyof typeof messages['zh-CN'];
export type Translate = (key: TranslationKey, variables?: Record<string, string | number>) => string;

type LanguageContextValue = {
  preference: AppLanguagePreference;
  language: AppLanguage;
  setPreference(preference: AppLanguagePreference): void;
  t: Translate;
};

const defaultContext: LanguageContextValue = {
  preference: 'system',
  language: 'zh-CN',
  setPreference: () => undefined,
  t: createTranslator('zh-CN')
};

const LanguageContext = createContext<LanguageContextValue>(defaultContext);

export function LanguageProvider(props: PropsWithChildren<{
  initialPreference?: AppLanguagePreference;
}>) {
  const [preference, setPreferenceState] = useState<AppLanguagePreference>(
    () => props.initialPreference ?? readLanguagePreference()
  );
  const [systemLanguage, setSystemLanguage] = useState(() => resolveAppLanguage('system'));
  const language = preference === 'system' ? systemLanguage : preference;

  useEffect(() => {
    applyAppLanguage(language);
  }, [language]);

  useEffect(() => {
    if (preference !== 'system') return;
    const updateSystemLanguage = () => setSystemLanguage(resolveAppLanguage('system'));
    window.addEventListener('languagechange', updateSystemLanguage);
    return () => window.removeEventListener('languagechange', updateSystemLanguage);
  }, [preference]);

  const setPreference = useCallback((nextPreference: AppLanguagePreference) => {
    writeLanguagePreference(nextPreference);
    setPreferenceState(nextPreference);
    if (nextPreference === 'system') setSystemLanguage(resolveAppLanguage('system'));
  }, []);
  const t = useMemo(() => createTranslator(language), [language]);
  const value = useMemo<LanguageContextValue>(() => ({
    preference,
    language,
    setPreference,
    t
  }), [language, preference, setPreference, t]);

  return <LanguageContext.Provider value={value}>{props.children}</LanguageContext.Provider>;
}

export function useAppLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}

function createTranslator(language: AppLanguage): Translate {
  return (key, variables) => {
    const template: string = messages[language][key] ?? messages['zh-CN'][key];
    if (variables === undefined) return template;
    return Object.entries(variables).reduce<string>(
      (result, [name, value]) => result.replaceAll(`{{${name}}}`, String(value)),
      template
    );
  };
}
